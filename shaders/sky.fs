// ============================================================================
//  Sky — фрагментный шейдер скайбокса
// ----------------------------------------------------------------------------
//  img/skybox.png — панорама 360x90 (512x128, 4:1): горизонт в середине
//  картинки, сверху небо, снизу земля. Из NDC-координат фрагмента и базиса
//  камеры (uForward/uRight/uUp) восстанавливаем направление луча и берём
//  из панорамы широту/долготу. Вертикальный охват всего 90 градусов,
//  поэтому выше +45° и ниже -45° текстурных данных нет: зенит и надир
//  дорисовываем плавными градиентами (без плоского "диска" из верхнего ряда
//  и без жёсткого шва на +45°). Шов по долготе убирает GL_REPEAT, а "землю"
//  из панорамы (нижняя половина) глушим туманом — под горизонтом рендерится
//  настоящий рельеф. Фильтрация LINEAR — гладкие градиенты без полос.
// ============================================================================

in vec2 vPos;

uniform sampler2D uSky;       // панорама неба
uniform vec3 uTint;           // тон неба (из map.json: sky.tint)
uniform vec3 uForward;        // базис камеры (вид)
uniform vec3 uRight;
uniform vec3 uUp;
uniform float uTanFov;        // tan(полуобзор)
uniform float uAspect;        // пропорции окна
uniform vec3 uFogColor;       // цвет горизонта (туман рельефа)
uniform vec3 uSunDir;         // направление на солнце (узел Sun)
uniform vec3 uSunColor;       // цвет солнца
uniform float uSunGlow;       // видимость солнечного диска 0..1 (гаснет в дождь)
// Процедурные облака: 2 октавы шума на плоскости 500 м над камерой
uniform sampler2D uNoise;     // img/noise.png (unit 1)
uniform vec2 uCamXZ;          // позиция камеры XZ (облака в мире, не на камере)
uniform float uTime;          // дрейф облаков
uniform float uClouds;        // покрытие 0..1 (cvar r_clouds)

out vec4 FragColor;

void main() {
    vec3 rd = normalize(uForward
                        + uRight * vPos.x * uTanFov * uAspect
                        + uUp * vPos.y * uTanFov);
    float u = 0.5 + atan(rd.z, rd.x) / 6.2831853;        // долгота
    float elev = asin(clamp(rd.y, -1.0, 1.0));           // угол над горизонтом
    // Панорама покрывает ±45°: v=1 (низ) = -45°, v=0 (верх) = +45°.
    float v = clamp(0.5 - elev * 0.63661977, 0.0, 1.0);
    vec3 col = texture(uSky, vec2(u, v)).rgb * uTint;
    // Купол: выше +45° текстуры нет (она 90°) — плавный градиент к цвету
    // зенита, чтобы купол читался объёмно, а не плоским залитым диском
    // из одной строки текстуры (и без жёсткого шва на самом (+45°)).
    float zenithT = smoothstep(0.785398163, 1.570796327, elev); // 0 на +45°, 1 у зенита
    float dark = 1.0 - 0.18 * smoothstep(0.785398163, 1.570796327, elev);
    vec3 zenith = texture(uSky, vec2(u, 0.0)).rgb * uTint;
    col = mix(col, zenith * dark, zenithT);
    // солнечный диск и ореол — там, где смотрит источник света;
    // в дождь (uSunGlow -> 0) солнце скрыто облаками
    float s = dot(rd, normalize(uSunDir));
    col += uSunColor * uSunGlow * (pow(max(s, 0.0), 600.0) * 4.0
                                 + pow(max(s, 0.0), 10.0) * 0.35);
    // --- Процедурные облака ------------------------------------------------
    // Плоскость 3000 м над камерой: параллакс медленный, у горизонта облака
    // НЕ разгоняются в «спидометр» и не заворачивают вниз (раньше слой был
    // на 500 м — проекция rd.xz/rd.y у горизонта улетала и рвал картинку).
    // Затухание широкое и раннее: ниже ~25° над горизонтом облаков нет.
    if (uClouds > 0.001 && rd.y > 0.05) {
        vec2 cuv = (uCamXZ + rd.xz / max(rd.y, 0.25) * 3000.0) / 2600.0;
        float n = texture(uNoise, cuv + vec2(uTime * 0.0011, uTime * 0.0007)).r * 0.65
                + texture(uNoise, cuv * 2.6 - vec2(uTime * 0.0018, 0.0)).r * 0.35;
        // Порог по покрытию: uClouds 0..1 -> чем больше, тем ниже порог
        float cov = smoothstep(0.78 - uClouds * 0.55, 0.95 - uClouds * 0.45, n);
        cov *= smoothstep(0.10, 0.40, rd.y);          // у горизонта тонут
        if (cov > 0.003) {
            float warm = pow(max(s, 0.0), 3.0);        // сторона солнца
            vec3 cc = mix(vec3(0.82, 0.84, 0.88),          // пасмурная сторона
                          vec3(1.05, 0.98, 0.9),           // к солнцу теплее
                          0.25 + 0.6 * warm);
            cc *= 0.75 + 0.25 * uSunGlow;              // в дождь — темнее
            col = mix(col, cc, cov * 0.5);             // деликатно, не в лоб
        }
    }
    // под горизонтом панорама — это земля, но у нас настоящий рельеф: глушим
    col = mix(col, uFogColor, smoothstep(0.46, 0.50, v));
    FragColor = vec4(col, 1.0);
}
