// ============================================================================
//  ObjectShadow — фрагментный шейдер объектов в карту теней
// ----------------------------------------------------------------------------
//  Прозрачный фон текстуры отбрасывается (иначе деревья кидали бы тень
//  целым прямоугольником квада).
// ============================================================================

in vec2 vUV;

uniform sampler2D uTex;

void main() {
    if (texture(uTex, vUV).a < 0.5) discard;
}
