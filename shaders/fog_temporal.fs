// ============================================================================
//  fog_temporal.fs — временное накопление полупроходного тумана
// ----------------------------------------------------------------------------
//  Марш тумана (volumetric.fs) джиттерится АНИМИРОВАННО (фаза каждый кадр):
//  в одиночном кадре это зерно, глаз его видит как мерцание на полупрозрачном
//  тумане. Здесь прошлый кадр тумана смешивается с текущим — шум усредняется
//  за несколько кадров, туман становится стабильным.
//  Анти-гостинг: история КЛАМПИТСЯ в AABB 3x3-соседей ТЕКУЩЕГО кадра —
//  при движении камеры/сцене шлейф не выходит за локальный разброс цвета.
//  RGBA8-текстура того же полразмера (цвет тумана + trans в альфе).
// ============================================================================

in vec2 vUV;

uniform sampler2D uCur;    // марш текущего кадра (полразмера)
uniform sampler2D uPrev;   // накопленный прошлый кадр
uniform float uBlend;      // вес истории (0.8 = ~5 кадров усреднения; 0 = выкл)

out vec4 FragColor;

void main() {
    vec4 c = texture(uCur, vUV);
    vec2 ts = 1.0 / vec2(textureSize(uCur, 0));
    // AABB соседей текущего кадра (3x3): допустимый диапазон для истории
    vec4 mn = c, mx = c;
    for (int y = -1; y <= 1; y++) {
        for (int x = -1; x <= 1; x++) {
            if (x == 0 && y == 0) continue;
            vec4 s = texture(uCur, vUV + vec2(float(x), float(y)) * ts);
            mn = min(mn, s);
            mx = max(mx, s);
        }
    }
    vec4 h = clamp(texture(uPrev, vUV), mn, mx);
    FragColor = mix(c, h, uBlend);
}
