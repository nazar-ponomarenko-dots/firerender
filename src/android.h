// ============================================================================
//  android.h — подготовка окружения под Android (см. android.c)
// ----------------------------------------------------------------------------
//  На Android ресурсы лежат внутри APK и fopen() их не видит. При старте
//  распаковываем их в приватное хранилище приложения (SDL_GetPrefPath) и
//  переходим туда chdir'ом — дальше весь движок работает как обычно:
//  относительные пути, config.cfg рядом, miniz-паки карт.
//  На остальных платформах — no-op.
// ============================================================================
#ifndef ANDROID_H
#define ANDROID_H

// Распаковать APK-assets в хранилище и сделать его рабочей папкой.
// Вызывается один раз в начале main(), до определения base_dir.
// Возвращает 1, если окружение подготовлено (Android), 0 — обычная платформа.
int fr_android_prepare(void);

#endif
