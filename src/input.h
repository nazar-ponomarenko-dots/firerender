// ============================================================================
//  input.h — ввод: события главного цикла и синхронизация режима мыши
// ----------------------------------------------------------------------------
//  Вынесено из main.c: разбор SDL-событий (консоль -> бинды -> ESC), ресайз
//  окна и переключение режима мыши/текстового ввода (меню <-> игра).
// ============================================================================
#ifndef INPUT_H
#define INPUT_H
#include <SDL3/SDL.h>
#include "game.h"

// Сохраняет окно и игровое состояние (для ресайза). Вызывать после
// создания окна и game_init.
void input_init(SDL_Window *win, Game *g);

// Разбор всех событий кадра: консоль, ресайз, бинды, ESC.
// Вызывать из главного цикла.
void input_process(void);

// Синхронизация режима мыши и text input с состоянием игры/меню/консоли.
void input_sync_mode(void);

// 1 — был получен SDL_EVENT_QUIT (главный цикл завершает работу).
int input_quit(void);

// Android/window lifecycle: background останавливает simulation/render/swap;
// resume сообщает один раз, чтобы главный цикл сбросил clock accumulator.
int input_background(void);
int input_take_resumed(void);

#endif
