// ============================================================================
//  touch.h — сенсорное управление (см. touch.c)
// ============================================================================
#ifndef TOUCH_H
#define TOUCH_H

#include <SDL3/SDL.h>

// Обрабатывает событие тача (SDL_EVENT_FINGER_*). Вызывается из input_process
// ПОСЛЕ console_event и только в состоянии игры (APP_PLAY).
// Возвращает 1, если событие поглощено тач-управлением.
int touch_event(const SDL_Event *ev);

// Переключение UI-режима (меню/консоль): включает синтетические мышиные
// события из тача (тапы по кнопкам меню) или отключает (в игре тач ведёт
// виртуальный джойстик и обзор). Вызывается из input_sync_mode.
void touch_set_ui_mode(int ui_mode);

// Кадровый апдейт: сбрасывает пульс прыжка от тапа. Вызывается раз в кадр.
void touch_frame(void);

// Забирает накопленную дельту обзора от свайпа (в пикселях окна).
// После чтения счётчики обнуляются. Вызывается из camera.c раз в кадр.
void touch_look_take(float *dx, float *dy);

// Рисует виртуальный джойстик поверх HUD (только когда палец на джойстике).
void touch_hud_draw(int vw, int vh);

// Сброс: палец «уплыл» из-за перехода в меню/консоль — отпустить всё.
void touch_reset(void);

// Есть ли тач-устройство (на десктопе 0 — модуль спит)
int touch_available(void);

#endif
